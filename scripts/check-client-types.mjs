/**
 * Preflight AND generator for the client typecheck.
 *
 * The client half types itself against declarations inside a dsh checkout
 * rather than installed packages (react, react/jsx-runtime and the client
 * runtime are host-provided externals and deliberately NOT dependencies of
 * this package). tsconfig.client.json therefore carries `${DSH_SRC}` tokens
 * in its `paths` — tsc does not expand tokens, so that file is a TEMPLATE.
 * This script is the only expander: it resolves DSH_SRC (env var, default
 * `~/dsh`), verifies every expanded target exists (failing loudly and by
 * name instead of surfacing a wall of TS2307), and writes the gitignored
 * tsconfig.client.local.json that `check:client` and `build:client` actually
 * pass to tsc.
 *
 * WHY A TEMPLATE AND NOT A LITERAL PATH: a literal put one developer's
 * identity into every copy of the tree (caught by review on the redaction
 * PR), and tsconfig has no expression evaluation of its own — so derivation
 * has to live here, the same treatment scripts/run-bundle.mjs applies to the
 * pnpm store path.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const templatePath = resolve(root, 'tsconfig.client.json')
const localPath = resolve(root, 'tsconfig.client.local.json')

const dshHome = resolve(process.env.DSH_SRC ?? `${homedir()}/dsh`).replace(/\\/g, '/')
const template = JSON.parse(readFileSync(templatePath, 'utf8'))
const paths = template.compilerOptions?.paths ?? {}

const expanded = {}
const missing = []
for (const [specifier, targets] of Object.entries(paths)) {
  expanded[specifier] = targets.map(t => t.replaceAll('${DSH_SRC}', dshHome))
  for (const target of expanded[specifier]) {
    if (!existsSync(resolve(root, target))) missing.push(`${specifier} -> ${target}`)
  }
}

if (missing.length > 0) {
  process.stderr.write(
    'check-client-types: the client typecheck needs declarations that are not on this machine.\n'
    + missing.map(line => `  MISSING  ${line}\n`).join('')
    + `\n(DSH_SRC resolved to: ${dshHome})\n`
    + 'These are BUILD-TIME-ONLY paths into a dsh source checkout (see BUILD-SPEC §6).\n'
    + 'Set DSH_SRC to your checkout, or skip the client build: the host half builds without it.\n',
  )
  process.exit(1)
}

// `paths` in an extending config REPLACES the parent's wholesale, so the
// local file only needs the expanded map (and its own baseUrl anchor).
const local = {
  '//': 'GENERATED by scripts/check-client-types.mjs — do not edit, do not commit. '
    + 'Expands the ${DSH_SRC} tokens of tsconfig.client.json for this machine.',
  extends: './tsconfig.client.json',
  compilerOptions: { baseUrl: '.', paths: expanded },
}
writeFileSync(localPath, JSON.stringify(local, null, 2) + '\n', 'utf8')
process.stdout.write(
  `check-client-types: ${Object.keys(paths).length} declaration path(s) present`
  + ` (DSH_SRC=${dshHome}); wrote tsconfig.client.local.json\n`,
)
